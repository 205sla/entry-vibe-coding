// Semantic validation before normalization can pad/drop params or invent IDs.
import fs from 'node:fs';
import path from 'node:path';

export function checkSpecReferences(input, registry, publicDir) {
    const issues = [];
    let malformed = false;
    const error = (where, msg) => issues.push({ severity: 'error', path: where, msg });
    const shapeError = (where, msg) => { malformed = true; error(where, msg); };
    if (!input || typeof input !== 'object' || Array.isArray(input)) {
        return { spec: {}, issues: [{ severity: 'error', path: 'spec', msg: 'spec must be an object' }], malformed: true };
    }
    const spec = { ...input };
    for (const key of ['objects', 'variables', 'lists', 'scenes', 'messages', 'functions']) {
        if (spec[key] === undefined) spec[key] = key === 'scenes' ? [{ name: '장면 1' }] : [];
        if (!Array.isArray(spec[key]) || spec[key].some(item => !item || typeof item !== 'object' || Array.isArray(item))) {
            shapeError(key, 'expected an array of objects');
            spec[key] = [];
        }
    }
    if (!spec.scenes.length) error('scenes', 'at least one scene is required');
    const records = (items, label) => {
        const map = new Map();
        items.forEach((item, index) => {
            if (!item || typeof item !== 'object') { shapeError(label + '[' + index + ']', 'expected an object'); return; }
            if (item.id == null) return; // optional IDs are generated by the builder
            if (typeof item.id !== 'string' || !item.id) error(label + '[' + index + '].id', 'id must be a non-empty string');
            else if (map.has(item.id)) error(label + '[' + index + '].id', 'duplicate id: ' + item.id);
            else map.set(item.id, item);
        });
        return map;
    };
    const objects = records(spec.objects, 'objects');
    const vars = records([...spec.variables, ...spec.lists], 'variables/lists');
    const lists = new Map([...vars].filter(([id]) => spec.lists.some(item => item.id === id) || vars.get(id).variableType === 'list'));
    const scalars = new Map([...vars].filter(([id]) => !lists.has(id)));
    const scenes = records(spec.scenes, 'scenes');
    const messages = records(spec.messages, 'messages');
    const functions = records(spec.functions, 'functions');
    const literal = value => {
        if (value && typeof value === 'object') {
            if (Object.hasOwn(value, '__field')) return value.__field;
            if (['text', 'number'].includes(value.type)) return value.params?.[0];
            return undefined; // computed reference: cannot prove its target statically
        }
        return value;
    };
    const ref = (value, map, where, kind) => {
        const id = literal(value);
        if (id === undefined) return;
        if (!map.has(String(id))) error(where, 'unknown ' + kind + ' reference: ' + id);
    };
    for (const [index, variable] of spec.variables.entries()) {
        if (variable.object != null) ref(variable.object, objects, 'variables[' + index + '].object', 'object');
    }
    const asset = (item, where, image) => {
        if (!item || typeof item !== 'object') { shapeError(where, 'asset must be an object'); return; }
        if (image && typeof item.svgString === 'string' && item.svgString.trim()) return;
        let file;
        if (item.path) file = item.path;
        else if (typeof item.fileurl === 'string' && /^(https?:|data:)/.test(item.fileurl)) {
            issues.push({ severity: 'warning', path: where, msg: 'external/data asset is not bundled or fetched by static validation' });
            return;
        } else if (typeof item.fileurl === 'string' && item.fileurl.startsWith('/')) {
            file = path.resolve(publicDir, item.fileurl.slice(1));
            if (!file.startsWith(publicDir + path.sep)) { error(where, 'asset escapes public directory'); return; }
        }
        if (typeof file !== 'string') { error(where, 'asset needs an existing path, public fileurl, or image svgString'); return; }
        try { if (!fs.statSync(file).isFile()) throw new Error('not a file'); }
        catch { error(where, 'asset file not found: ' + file); }
    };
    const parseThreads = (value, where) => {
        if (typeof value === 'string') {
            try { value = JSON.parse(value); } catch { shapeError(where, 'invalid script JSON'); return []; }
        }
        value ??= [[]];
        if (!Array.isArray(value) || value.some(thread => !Array.isArray(thread))) {
            shapeError(where, 'script/content must be a two-dimensional block array'); return [];
        }
        return value;
    };
    spec.objects = spec.objects.map((object, index) => {
        const where = 'objects[' + index + ']';
        if (object.scene != null && !scenes.has(object.scene) && !spec.scenes.some(scene => scene.name === object.scene)) error(where + '.scene', 'unknown scene reference: ' + object.scene);
        if ((object.objectType || 'sprite') === 'sprite' && !(object.pictures?.length)) {
            asset({ path: path.join(publicDir, 'images', 'blank', 'placeholder.svg') }, where + '.pictures(default)', true);
        }
        for (const key of ['pictures', 'sounds']) {
            const items = object[key] ?? [];
            if (!Array.isArray(items)) { shapeError(where + '.' + key, 'expected asset array'); continue; }
            if (items.some(item => !item || typeof item !== 'object')) { shapeError(where + '.' + key, 'expected asset objects'); continue; }
            records(items, where + '.' + key);
            items.forEach((item, i) => asset(item, where + '.' + key + '[' + i + ']', key === 'pictures'));
        }
        return { ...object, script: parseThreads(object.script, where + '.script') };
    });
    spec.functions = spec.functions.map((fn, index) => ({ ...fn, content: parseThreads(fn.content, 'functions[' + index + '].content') }));
    function walk(node, where, object, fn) {
        if (!node || typeof node !== 'object' || Array.isArray(node) || typeof node.type !== 'string') { shapeError(where, 'expected a block with type'); return; }
        for (const key of ['params', 'statements']) {
            if (node[key] !== undefined && !Array.isArray(node[key])) { shapeError(where + '.' + key, 'expected an array'); return; }
        }
        if (node.type.startsWith('func_')) ref(node.type.slice(5), functions, where, 'function');
        const metadata = registry[node.type];
        for (const [index, slot] of (metadata?.params || []).entries()) {
            if (!slot) continue;
            const target = { variables: scalars, lists, messages, scenes }[slot.menu];
            if (target && node.params?.[index] != null) ref(node.params[index], target, where + '.params[' + index + ']', slot.menu);
        }
        if (['get_func_variable', 'set_func_variable'].includes(node.type)) {
            const locals = new Map((fn?.localVariables || []).filter(item => item && typeof item === 'object').map(item => [item.id, item]));
            ref(node.params?.[0], locals, where + '.params[0]', 'function local variable');
        }
        // Field sentinel is not an escape hatch around checking references.
        for (const [index, value] of (node.params || []).entries()) {
            if (value && typeof value === 'object' && !Object.hasOwn(value, '__field')) walk(value, where + '.params[' + index + ']', object, fn);
        }
        for (const [index, thread] of (node.statements || []).entries()) {
            if (!Array.isArray(thread)) { shapeError(where + '.statements[' + index + ']', 'expected block array'); continue; }
            thread.forEach((block, i) => walk(block, where + '.statements[' + index + '][' + i + ']', object, fn));
        }
    }
    spec.objects.forEach((object, index) => object.script.forEach((thread, t) => thread.forEach((block, b) => walk(block, 'objects[' + index + '].script[' + t + '][' + b + ']', object, null))));
    spec.functions.forEach((fn, index) => {
        if (!Array.isArray(fn.localVariables ?? [])) { shapeError('functions[' + index + '].localVariables', 'expected array'); return; }
        records(fn.localVariables || [], 'functions[' + index + '].localVariables');
        fn.content.forEach((thread, t) => thread.forEach((block, b) => walk(block, 'functions[' + index + '].content[' + t + '][' + b + ']', null, fn)));
    });
    return { spec, issues, malformed };
}
