//
// 환산 기준: 원작 값 / 256 = px/frame.
//   최대 걷기 속도  0x18800 → 1.5625 px/f
//   최대 달리기     0x28000 → 2.5    px/f
//   걷기 가속       0x00098 → 0.037  px/f²
//   마찰(감속)      0x000D0 → 0.05   px/f²
//   점프 초기 속도  약 4.0 px/f (버튼 유지 시 중력 완화로 체공 연장)
//
// 이 값들은 **참조 작품과 같은 체감**을 목표로 한 근사다. 원작 코드를 옮긴 게 아니라
// 공개된 수치 관계(걷기:달리기 ≈ 1:1.6, 점프 높이 ≈ 4~5 칸)를 재현한 것이다.
// 체감을 맞추려면 속도·중력·거리가 전부 타일 배율에 비례해야 한다 — 그래서 **모든 길이·속도
// 상수를 `S` 로 유도**한다. 하드코딩된 px 이 하나라도 남으면 타일 크기를 바꿀 때 조용히 어긋난다.
//
// 2026-07-31: Phase 2-1 스파이크로 TILE 32 → **24** (S 2 → 1.5). 근거·실측은
// `기획/Phase2-4-계획.md` §4. 세로 9 행 → 11 행을 얻는 게 목적이고, 20px(13 행)은
// 지하 밀도에서 53.5fps 로 탈락했다.

